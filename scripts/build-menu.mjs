const slug = (s) => s.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

const categories = [];
const items = [];
for (const [id, [name, emoji, list]] of Object.entries(menu)) {
  categories.push({ id, name, emoji });
  for (const [iname, price, description, flags = ""] of list) {
    const itemSlug = slug(iname);
    items.push({
      id: itemSlug,
      categoryId: id,
      name: iname,
      price,
      description,
      image: `/menu/${itemSlug}.jpg`,
      ...(flags.includes("*") && { popular: true }),
      ...(flags.includes("s") && { spicy: true }),
      ...(flags.includes("j") && { jain: true }),
      ...(flags.includes("n") && { isNew: true }),
    });
  }
}

const dup = items.map((i) => i.id).filter((id, i, a) => a.indexOf(id) !== i);
if (dup.length) throw new Error("duplicate ids: " + dup.join(", "));

const out = { ...base, categories, items };
writeFileSync("src/data/menu.json", JSON.stringify(out, null, 2));
console.log(`${items.length} items in ${categories.length} categories`);
